#!/usr/bin/env node
/**
 * Vendors Nerd Font icon outlines so keys draw the icons agents put in their
 * titles (OMP: `π <icon> POSTER: …`) on any machine, installed fonts or not.
 *
 *   npm run icons:nerd
 *
 * Downloads the pinned Symbols Nerd Font release, extracts every private-use
 * glyph (BMP U+E000–U+F8FF and plane 15, which holds the Material Design set),
 * and writes src/core/render/nerdGlyphs.ts: base64 brotli JSON of codepoint
 * hex → [advance, path], both at font size 24 with the baseline at y = 0.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { brotliCompressSync, constants } from "node:zlib";
import opentype from "opentype.js";

const VERSION = "v3.4.0";
const URL = `https://github.com/ryanoasis/nerd-fonts/releases/download/${VERSION}/NerdFontsSymbolsOnly.tar.xz`;
const SIZE = 24;

const here = dirname(fileURLToPath(import.meta.url));
const work = mkdtempSync(join(tmpdir(), "nerd-glyphs-"));
try {
  const res = await fetch(URL);
  if (!res.ok) throw new Error(`download failed: ${res.status} ${URL}`);
  writeFileSync(join(work, "symbols.tar.xz"), Buffer.from(await res.arrayBuffer()));
  execFileSync("tar", ["xf", "symbols.tar.xz", "SymbolsNerdFont-Regular.ttf"], { cwd: work });
  const font = opentype.parse(readFileSync(join(work, "SymbolsNerdFont-Regular.ttf")).buffer);

  const scale = SIZE / font.unitsPerEm;
  const glyphs = {};
  for (const [cp, index] of Object.entries(font.tables.cmap.glyphIndexMap)) {
    const c = Number(cp);
    if (!((c >= 0xe000 && c <= 0xf8ff) || (c >= 0xf0000 && c <= 0xffffd))) continue;
    const glyph = font.glyphs.get(index);
    const d = glyph.getPath(0, 0, SIZE).toPathData(1);
    if (d) glyphs[c.toString(16).toUpperCase()] = [Math.round(glyph.advanceWidth * scale * 10) / 10, d];
  }

  const packed = brotliCompressSync(JSON.stringify(glyphs), {
    params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
  }).toString("base64");
  const ts = `// AUTO-GENERATED by scripts/gen-nerd-glyphs.mjs — do not edit by hand.
// Symbols Nerd Font ${VERSION} (https://www.nerdfonts.com; MIT, bundled icon sets
// under their own licenses): base64 brotli JSON of codepoint hex →
// [advance, path] at font size ${SIZE}, baseline at y = 0.
export const NERD_GLYPHS_BR = "${packed}";
`;
  const dest = join(here, "..", "src", "core", "render", "nerdGlyphs.ts");
  writeFileSync(dest, ts);
  console.log(`Wrote ${Object.keys(glyphs).length} Nerd Font glyphs (${(ts.length / 1024).toFixed(0)} KB) → ${dest}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
